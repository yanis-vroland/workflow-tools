#!/usr/bin/env bash
# Spec 010, CA5 et CA6 côté pub : petite application Flutter fictive (hors
# FieldOps) dont pubspec.lock contient une dépendance transitive visée par un avis
# public réel, vérifié le 2026-10-20 sur OSV.dev :
#   http 0.12.2 (transitive), avis GHSA-4rgh-jx4f-qfcq (alias CVE-2020-35669),
#   première version corrigée 0.13.3 ;
# introduite par la dépendance directe google_fonts 1.1.0, dont le pubspec publié
# sur pub.dev déclare `http: ^0.12.0+2` après une dépendance imbriquée
# (`flutter: {sdk: flutter}`) : le lien direct/transitive n'est établi qu'en
# lisant toutes les dépendances déclarées.
set -euo pipefail

if [ -n "$(ls -A .)" ]; then
  echo "Le répertoire de travail de l'eval devrait être vide." >&2
  exit 1
fi

mkdir -p lib

cat >pubspec.yaml <<'YAML'
name: carnet_releves
description: Carnet de relevés de compteurs (application fictive).
publish_to: "none"
version: 0.4.0+7

environment:
  sdk: ">=2.12.0 <3.0.0"

dependencies:
  flutter:
    sdk: flutter
  google_fonts: 1.1.0
YAML

cat >pubspec.lock <<'LOCK'
# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
  crypto:
    dependency: transitive
    description:
      name: crypto
      url: "https://pub.dartlang.org"
    source: hosted
    version: "2.1.5"
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
  google_fonts:
    dependency: "direct main"
    description:
      name: google_fonts
      url: "https://pub.dartlang.org"
    source: hosted
    version: "1.1.0"
  http:
    dependency: transitive
    description:
      name: http
      url: "https://pub.dartlang.org"
    source: hosted
    version: "0.12.2"
  path_provider:
    dependency: transitive
    description:
      name: path_provider
      url: "https://pub.dartlang.org"
    source: hosted
    version: "1.6.28"
sdks:
  dart: ">=2.12.0 <3.0.0"
  flutter: ">=1.17.0"
LOCK

cat >lib/main.dart <<'DART'
import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

void main() => runApp(const CarnetApp());

class CarnetApp extends StatelessWidget {
  const CarnetApp({Key? key}) : super(key: key);

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Carnet de relevés',
      theme: ThemeData(textTheme: GoogleFonts.latoTextTheme()),
      home: const Scaffold(body: Center(child: Text('Aucun relevé'))),
    );
  }
}
DART

export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null TZ=UTC
export GIT_AUTHOR_NAME="Nora Belkacem" GIT_AUTHOR_EMAIL="nora.belkacem@example.invalid"
export GIT_COMMITTER_NAME="$GIT_AUTHOR_NAME" GIT_COMMITTER_EMAIL="$GIT_AUTHOR_EMAIL"
export GIT_AUTHOR_DATE="2026-09-15T10:00:00Z" GIT_COMMITTER_DATE="2026-09-15T10:00:00Z"
git -c core.hooksPath=/dev/null init -q -b main
git -c core.hooksPath=/dev/null add pubspec.yaml pubspec.lock lib/main.dart
git -c core.hooksPath=/dev/null -c commit.gpgsign=false commit -q -m "feat: carnet de relevés"
